from trending.models import Repo

SYSTEM_PROMPT = """你是一个资深技术趋势分析师。根据提供的 GitHub Trending 仓库列表，生成一份深度中文技术报告。

要求：
1. 报告以 Markdown 格式输出
2. **趋势总览**：用一段话（200字左右）概括本期整体趋势，分析当前技术热点方向、开发者注意力集中在哪些领域，并与近期趋势对比说明变化
3. **本期项目与前沿方向分析**：先提炼出本期呈现的 2-4 个技术方向/主题（如 Agent 工程化、推理优化、开源硬件等），然后在每个方向下列出代表性项目，每个项目用 3-5 句话深度介绍：
   - 项目做什么、核心能力
   - 解决什么痛点、为什么这个时刻值得关注
   - 背后反映的技术趋势或行业需求
   - 技术架构的关键设计（如果有公开信息）
4. **值得关注的新星**：从星数不高但有潜力的项目中，挑选 2-3 个讲解其创新点和成长潜力
5. **开发工具生态变化**：分析开发工具/基础设施类项目，说明它们反映了怎样的工作流变革
6. 只输出报告正文，不要前言或后记
7. 风格：专业、有洞察力、帮助读者理解"发生了什么"和"为什么重要"
"""


def format_repos_text(repos: list[Repo]) -> str:
    """将仓库列表格式化为供 AI 阅读的文本"""
    lines = []
    for i, r in enumerate(repos, 1):
        lines.append(
            f"{i}. **{r.full_name}** | ⭐{r.total_stars} (+{r.stars_period})"
            f" | 语言: {r.language or '未知'}"
            f"\n   {r.description or '(无描述)'}"
        )
    return "\n".join(lines)
